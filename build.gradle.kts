/**
 * Writes `BuildConfig.kt` with the version from this script and the time of the build. The file lives under
 * `build/` and is therefore not versioned. The timestamp is taken when the task runs, so the task is never
 * up to date and the file is rewritten on every build.
 */
abstract class GenerateBuildConfig : DefaultTask() {
    @get:Input
    abstract val version: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    init {
        outputs.upToDateWhen { false }
    }

    @TaskAction
    fun generate() {
        val file = outputDir.get().file("bayern/kickner/dirl/BuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package bayern.kickner.dirl
            |
            |/** Generated by Gradle on every build (see build.gradle.kts). Do not edit, do not commit. */
            |object BuildConfig {
            |    /** The `version` from build.gradle.kts. */
            |    const val VERSION = "${version.get()}"
            |
            |    /** Time of the build as Unix timestamp in milliseconds. */
            |    const val BUILD_TIME = ${System.currentTimeMillis()}L
            |}
            |""".trimMargin()
        )
    }
}

val generateBuildConfig = tasks.register<GenerateBuildConfig>("generateBuildConfig") {
    version.set(project.version.toString())
    outputDir.set(layout.buildDirectory.dir("generated/buildConfig/kotlin"))
}

// Registering the task as source directory makes compileKotlin (and with it test) depend on it
